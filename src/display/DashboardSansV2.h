// Bold faces use the same compact glyph table layout. Bitmaps are generated
// from the approved V2 reference raster at their native target sizes.
extern const Face Bold16Face;
extern const Face Bold22Face;
extern const Face Bold28Face;
extern const Face Bold36Face;

inline const Face* face(uint8_t px, Weight weight) {
    if (weight == Weight::Regular) {
        if (px == 12) return &Regular12Face;
        if (px == 16) return &Regular16Face;
        return nullptr;
    }
    if (px == 16) return &Bold16Face;
    if (px == 22) return &Bold22Face;
    if (px == 28) return &Bold28Face;
    if (px == 36) return &Bold36Face;
    return nullptr;
}

inline bool readGlyph(const Face& f, char ch, Glyph& out) {
    const uint8_t code = static_cast<uint8_t>(ch);
    for (uint8_t i = 0; i < f.glyphCount; ++i) {
        memcpy_P(&out, &f.glyphs[i], sizeof(Glyph));
        if (out.code == code) return true;
    }
    return false;
}

inline void drawGlyph(IDisplay& d, int16_t x, int16_t top, const Face& f, const Glyph& g, uint16_t color) {
    if (g.w == 0 || g.h == 0) return;
    for (uint8_t yy = 0; yy < g.h; ++yy) {
        for (uint8_t xx = 0; xx < g.w; ++xx) {
            const uint16_t bitIndex = static_cast<uint16_t>(yy) * g.w + xx;
            const uint8_t byte = pgm_read_byte(f.bitmap + g.bitmapOffset + bitIndex / 8u);
            if ((byte & (0x80u >> (bitIndex & 7u))) != 0)
                d.drawPixel(x + g.xOffset + xx, top + g.yOffset + yy, color);
        }
    }
}

inline int16_t textWidth(const String& text, uint8_t px, Weight weight) {
    const Face* f = face(px, weight);
    if (!f) return 0;
    int16_t width = 0;
    Glyph g;
    for (size_t i = 0; i < text.length(); ++i)
        if (readGlyph(*f, text[i], g)) width += g.advance;
    return width;
}

inline void drawText(IDisplay& d, int16_t x, int16_t top, const String& text,
                     uint8_t px, Weight weight, uint16_t color = 0) {
    const Face* f = face(px, weight);
    if (!f) return;
    Glyph g;
    for (size_t i = 0; i < text.length(); ++i) {
        if (!readGlyph(*f, text[i], g)) continue;
        drawGlyph(d, x, top, *f, g, color);
        x += g.advance;
    }
}

