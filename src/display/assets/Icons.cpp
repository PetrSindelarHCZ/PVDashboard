enum class WeatherKind : uint8_t {
    Clear,
    Partly,
    Cloudy,
    Rain,
    Snow,
    Fog,
    Thunder
};

WeatherKind classify(uint8_t code) {
    if (code == 45 || code == 48) return WeatherKind::Fog;
    if (code >= 95) return WeatherKind::Thunder;
    if ((code >= 71 && code <= 77) || code == 85 || code == 86) return WeatherKind::Snow;
    if ((code >= 51 && code <= 67) || (code >= 80 && code <= 82)) return WeatherKind::Rain;
    if (code == 0) return WeatherKind::Clear;
    if (code == 1 || code == 2) return WeatherKind::Partly;
    return WeatherKind::Cloudy;
}

Bitmap makeWeatherBitmap(WeatherKind kind, WeatherSize size) {
    const int16_t pixels = size == WeatherSize::Small24 ? 24 :
                           size == WeatherSize::Medium40 ? 40 : 56;

    switch (size) {
        case WeatherSize::Small24:
            switch (kind) {
                case WeatherKind::Clear:   return {kWeatherClear24, 24, 24};
                case WeatherKind::Partly:  return {kWeatherPartly24, 24, 24};
                case WeatherKind::Cloudy:  return {kWeatherCloudy24, 24, 24};
                case WeatherKind::Rain:    return {kWeatherRain24, 24, 24};
                case WeatherKind::Snow:    return {kWeatherSnow24, 24, 24};
                case WeatherKind::Fog:     return {kWeatherFog24, 24, 24};
                case WeatherKind::Thunder: return {kWeatherThunder24, 24, 24};
            }
            break;
        case WeatherSize::Medium40:
            switch (kind) {
                case WeatherKind::Clear:   return {kWeatherClear40, 40, 40};
                case WeatherKind::Partly:  return {kWeatherPartly40, 40, 40};
                case WeatherKind::Cloudy:  return {kWeatherCloudy40, 40, 40};
                case WeatherKind::Rain:    return {kWeatherRain40, 40, 40};
                case WeatherKind::Snow:    return {kWeatherSnow40, 40, 40};
                case WeatherKind::Fog:     return {kWeatherFog40, 40, 40};
                case WeatherKind::Thunder: return {kWeatherThunder40, 40, 40};
            }
            break;
        case WeatherSize::Large56:
            switch (kind) {
                case WeatherKind::Clear:   return {kWeatherClear56, 56, 56};
                case WeatherKind::Partly:  return {kWeatherPartly56, 56, 56};
                case WeatherKind::Cloudy:  return {kWeatherCloudy56, 56, 56};
                case WeatherKind::Rain:    return {kWeatherRain56, 56, 56};
                case WeatherKind::Snow:    return {kWeatherSnow56, 56, 56};
                case WeatherKind::Fog:     return {kWeatherFog56, 56, 56};
                case WeatherKind::Thunder: return {kWeatherThunder56, 56, 56};
            }
            break;
    }

    return {nullptr, pixels, pixels};
}

