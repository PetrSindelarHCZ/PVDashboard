const uint8_t* bitmapForWmo(uint8_t weatherCode) {
    if (weatherCode == 0) return wi_day_sunny_48x48;
    if (weatherCode == 1 || weatherCode == 2) return wi_day_cloudy_48x48;
    if (weatherCode == 3) return wi_cloudy_48x48;
    if (weatherCode == 45 || weatherCode == 48) return wi_day_fog_48x48;
    if ((weatherCode >= 71 && weatherCode <= 77) || weatherCode == 85 || weatherCode == 86) {
        return wi_day_snow_48x48;
    }
    if (weatherCode >= 95) return wi_day_thunderstorm_48x48;
    if ((weatherCode >= 51 && weatherCode <= 67) || (weatherCode >= 80 && weatherCode <= 82)) {
        return wi_day_rain_48x48;
    }
    return wi_cloudy_48x48;
}

